// The project lives in Google Drive, which drops hidden "Icon\r" files into every folder.
// AAPT rejects them as resources, so remove them before each build.
val removeDriveIconFiles by tasks.registering {
    val sourceDir = layout.projectDirectory.dir("src").asFile
    doLast {
        sourceDir.walkTopDown()
            .filter { it.isFile && it.name == "Icon\r" }
            .forEach { it.delete() }
    }
}
tasks.named("preBuild") { dependsOn(removeDriveIconFiles) }

